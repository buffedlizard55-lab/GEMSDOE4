def build_metric(ev: dict) -> str:
    ms = ev.get("metric_strategy")
    body = [f"""<h2>Definition</h2>
<p>Scoring is a <b>distance-weighted Tversky index</b> with α=0.2, β=0.8 and a triangular kernel of
range R=300 m (3 px at 100 m) — <a href="{PROB}#performance-metric">official definition</a>.
Our implementation is <code>src/metrics.py</code>; its self-test checks it against a brute-force
transcription of the formulas and reproduces the worked example's 0.60.</p>
<pre class="math">TP_w = Σ<sub>g∈G</sub> max<sub>x:d(x,g)≤R</sub> p(x)·k(d(x,g))
FP_w = Σ<sub>x:p(x)&gt;0</sub> p(x)·[1 − max<sub>g∈G</sub> k(d(x,g))]
FN_w = Σ<sub>g∈G</sub> [1 − max<sub>x:d(x,g)≤R</sub> p(x)·k(d(x,g))]
DTI  = TP_w / (TP_w + α·FP_w + β·FN_w + ε)</pre>

<h2>The rearrangement that matters</h2>
<p>From the two sums, <code>TP_w + FN_w = |G|</code> holds <em>identically</em>, for any prediction.
Substituting:</p>
<pre class="math big">DTI = TP_w / ( 0.2·(TP_w + FP_w) + 0.8·|G| )</pre>
<p>So <code>TP_w</code> and <code>FP_w</code> enter with the <b>same coefficient</b>. Probability mass
costs the same wherever you put it; it earns credit only when it is the strongest mass within 3 px of
a ground-truth pixel. And <code>TP_w</code> saturates at 1 per ground-truth pixel, so extra mass on an
already-covered fault is pure cost. <code>scripts/metric_strategy.py</code> asserts this identity
against the direct computation on every row below.</p>"""]

