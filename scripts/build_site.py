def e(x) -> str:
    return html.escape(str(x))


def fmt_bytes(n) -> str:
    try:
        n = float(n)
    except Exception:
        return "—"
    for u in ("B", "KB", "MB", "GB"):
        if n < 1024 or u == "GB":
            return f"{n:,.1f} {u}" if u != "B" else f"{n:,.0f} B"
        n /= 1024
    return f"{n:.1f} GB"


